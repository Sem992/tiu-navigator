def has_display_value(value):
    """Return False for empty or placeholder metadata so empty rows are not shown."""
    if value is None:
        return False
    text = str(value).strip()
    if not text:
        return False
    normalized = text.casefold().replace("ё", "е")
    placeholders = (
        "информация уточняется",
        "требует уточнения",
        "требует проверки",
        "не подтверждено",
        "не подтверждена",
        "не подтверждены",
        "не указано",
        "не указана",
        "нет данных",
        "уточняется",
        "указаны в ответе",
        "—",
        "-"
    )
    return not any(marker in normalized for marker in placeholders)

@st.cache_data(ttl=86400, show_spinner=False)
def geocode_campuses():
    """Resolve address-level coordinates once per day; exact building pins still need field verification."""
    from geopy.geocoders import Nominatim
    from geopy.extra.rate_limiter import RateLimiter
    geolocator = Nominatim(user_agent="tiu_navigator_student_project")
    geocode = RateLimiter(geolocator.geocode, min_delay_seconds=1.1, swallow_exceptions=True)
    results = []
    for item in CAMPUS_LOCATIONS:
        try:
            point = geocode(item["query"], exactly_one=True, timeout=12)
            if point:
                results.append({**item, "lat": point.latitude, "lon": point.longitude})
        except Exception:
            continue
    return results

